export function adminPageInteriorGlobalText(value: string, language: AdminLanguage): string {
  const exact = T[value]?.[language];
  if (exact) return exact;

  // Keep common admin chrome translated even when the UI adds a dynamic value.
  const patterns: Array<[RegExp, (m: RegExpMatchArray) => string]> = [
    [/^Search\s+(.+)$/i, m => translateDynamic('Search', m[1], language)],
    [/^Add\s+(.+)$/i, m => translateDynamic('Add', m[1], language)],
    [/^Edit\s+(.+)$/i, m => translateDynamic('Edit', m[1], language)],
    [/^View\s+(.+)$/i, m => translateDynamic('View', m[1], language)],
    [/^Delete\s+(.+)$/i, m => translateDynamic('Delete', m[1], language)],
    [/^No\s+(.+)\s+found\.?$/i, m => noFound(m[1], language)],
    [/^(\d+)\s+selected$/i, m => `${m[1]} ${T['selected'][language]}`],
    [/^(\d+)\s+total$/i, m => `${m[1]} ${T['Total'][language]}`],
    [/^Page\s+(\d+)\s+of\s+(\d+)$/i, m => `${T['Page'][language]} ${m[1]} ${T['of'][language]} ${m[2]}`],
    [/^Showing\s+(\d+)\s*[–-]\s*(\d+)\s+of\s+(\d+)$/i, m => `${T['Showing'][language]} ${m[1]}–${m[2]} ${T['of'][language]} ${m[3]}`]
  ];
  for (const [pattern, resolver] of patterns) {
    const match = value.match(pattern);
    if (match) return resolver(match);
  }
  return value;
}

function translateDynamic(action: string, subject: string, language: AdminLanguage): string {
  const translatedAction = T[action]?.[language] ?? action;
  const exactSubject = T[subject]?.[language];
  return exactSubject ? `${translatedAction} ${exactSubject}` : `${translatedAction} ${subject}`;
}

function noFound(subject: string, language: AdminLanguage): string {
  const exact = T[subject]?.[language];
  const noun = exact ?? subject;
  const forms: Record<AdminLanguage, string> = {
    en: `No ${noun.toLowerCase()} found.`,
    mk: `Не се пронајдени ${noun.toLowerCase()}.`,
    sq: `Nuk u gjetën ${noun.toLowerCase()}.`,
    de: `Keine ${noun.toLowerCase()} gefunden.`
  };
  return forms[language];
}
